"""Chat Completions request parameters, usage parsing and billing-error detection.

Provider-agnostic: nothing here branches on the endpoint, only on the MODEL NAME (auto-detection)
and on explicit settings. Used by llm/client.py (in-process calls) and infra/llm_proxy.py (GEPA's
calls), so both paths send the same parameters and record the same usage breakdown.
No `openai` import (llm/client.py is the only module allowed to import it).

Facts below were checked against OpenAI's official docs on 2026-11-14 (sources in the report and
inline):
  * `max_tokens` "is now deprecated in favor of `max_completion_tokens`, and is not compatible with
    o-series models"; `max_completion_tokens` bounds "visible output tokens and reasoning tokens"
    (Chat Completions API reference, developers.openai.com/api/reference/.../chat/completions/create).
  * `reasoning_effort` values on Chat Completions: none, minimal, low, medium, high, xhigh, max;
    "Not all reasoning models support every value" (same page; openai SDK 3.51.0
    types/shared/reasoning_effort.py has the same Literal).
  * "When reasoning effort is not `none`, remove `temperature`, `top_p`, and `top_logprobs`. For
    Chat Completions, also remove `logprobs`." (developers.openai.com/api/docs/guides/latest-model).
  * usage: `prompt_tokens_details.cached_tokens` ("Cached tokens present in the prompt", a subset of
    prompt_tokens) and `completion_tokens_details.reasoning_tokens` ("Tokens generated by the model
    for reasoning", a subset of completion_tokens, billed as output).
  * Billing errors are HTTP 429 with `error.type` possibly `insufficient_quota` and `error.code` one
    of the codes in BILLING_ERROR_CODES; "Retrying billing, spend, or quota errors won't restore API
    access." (developers.openai.com/api/docs/guides/error-codes).

Resolution order for every setting: explicit config (RunConfig.llm) > env var > auto default.
  token_param       LLM_TOKEN_PARAM       auto | max_tokens | max_completion_tokens
  reasoning_effort  LLM_REASONING_EFFORT  one of REASONING_EFFORTS; unset = not sent
  temperature       LLM_TEMPERATURE       float; unset = not sent
  reasoning_model   LLM_REASONING_MODEL   true | false; unset = auto by model name
Auto: a reasoning model (REASONING_MODEL_RE: o1/o3/o4..., gpt-5*, gpt-6*, except *-chat*) gets
max_completion_tokens and no temperature / top_p / logprobs / top_logprobs (unless
reasoning_effort is "none"); any other model gets max_tokens, which is what vLLM / other
OpenAI-compatible servers receive today. reasoning_effort set for a non-reasoning model is not
sent (recorded in `dropped`).
"""

from __future__ import annotations

import os
import re
import warnings
from dataclasses import asdict, dataclass, field
from typing import Any, Mapping

TOKEN_PARAMS = ("auto", "max_tokens", "max_completion_tokens")
REASONING_EFFORTS = ("none", "minimal", "low", "medium", "high", "xhigh", "max")
# o1, o3-mini, o4-mini, gpt-5, gpt-5-mini, gpt-5.4-nano, gpt-6.1-terra ... (optionally "openai/" prefixed)
REASONING_MODEL_RE = re.compile(r"^(?:[\w.-]+/)?(?:o\d+(?:$|[-.])|gpt-[5-9])", re.IGNORECASE)
NON_REASONING_RE = re.compile(r"-chat\b", re.IGNORECASE)  # gpt-5-chat-latest was a non-reasoning model
REASONING_REJECTED = ("temperature", "top_p", "logprobs", "top_logprobs")

# error.code / error.type values that mean "no more money": never retried.
BILLING_ERROR_CODES = frozenset({
    "insufficient_quota",
    "credit_balance_exhausted",
    "organization_spend_limit_exceeded",
    "project_spend_limit_exceeded",
    "organization_usage_limit_exceeded",
})

ENV = {"token_param": "LLM_TOKEN_PARAM", "reasoning_effort": "LLM_REASONING_EFFORT",
       "temperature": "LLM_TEMPERATURE", "reasoning_model": "LLM_REASONING_MODEL",
       "thinking": "LLM_THINKING"}


class BillingError(Exception):
    """The provider refused for billing / quota / spend-limit reasons. Not retryable: stops the run."""

    def __init__(self, message: str, *, status: int | None = None, code: str | None = None):
        super().__init__(
            f"billing/quota error from the LLM provider (HTTP {status}, {code}): {message}. "
            "Retrying cannot help: check the account's credits and spend limits, then rerun.")
        self.status, self.code = status, code


def is_billing_error(code: Any = None, type_: Any = None) -> bool:
    return any(isinstance(x, str) and x in BILLING_ERROR_CODES for x in (code, type_))


def billing_error_from_body(status: int | None, body: Any) -> BillingError | None:
    """BillingError if an OpenAI-style error body ({"error": {...}} or the inner dict) is a billing error."""
    err = body.get("error", body) if isinstance(body, dict) else None
    if not isinstance(err, dict):
        return None
    code, type_ = err.get("code"), err.get("type")
    if not is_billing_error(code, type_):
        return None
    return BillingError(str(err.get("message") or "")[:500], status=status,
                        code=code if is_billing_error(code) else type_)


def is_reasoning_model(model: str | None) -> bool:
    m = (model or "").strip()
    return bool(REASONING_MODEL_RE.match(m)) and not NON_REASONING_RE.search(m)


@dataclass(frozen=True)
class ChatParams:
    """Resolved per-run request parameters (identical for agent and sleep calls)."""

    model: str | None
    reasoning_model: bool
    token_param: str                    # max_tokens | max_completion_tokens (resolved)
    token_param_setting: str = "auto"   # what was asked for: auto | max_tokens | max_completion_tokens
    reasoning_effort: str | None = None
    temperature: float | None = None
    thinking: bool | None = None        # vLLM/Qwen only: chat_template_kwargs enable_thinking
    dropped: tuple[str, ...] = field(default_factory=tuple)  # settings not sent (unsupported by the model)
    sources: dict = field(default_factory=dict)             # setting -> "config" | "env" | "auto"

    @property
    def strips_sampling(self) -> bool:
        return self.reasoning_model and self.reasoning_effort != "none"

    def request_kwargs(self, max_tokens: int) -> dict:
        kw: dict[str, Any] = {self.token_param: int(max_tokens)}
        if self.reasoning_effort is not None:
            kw["reasoning_effort"] = self.reasoning_effort
        if self.temperature is not None:
            kw["temperature"] = self.temperature
        if self.thinking is not None:
            kw["extra_body"] = {"chat_template_kwargs": {"enable_thinking": self.thinking}}
        return kw

    def apply_to_body(self, body: dict) -> dict:
        """Rewrite a client's request body (proxy path): token key, reasoning_effort, sampling params.

        With token_param_setting "auto" a non-reasoning model keeps the client's key (default
        max_tokens); otherwise the resolved key is forced. Returns the same dict, modified."""
        key = self.token_key_for(body)
        mct, mt = body.pop("max_completion_tokens", None), body.pop("max_tokens", None)
        value = mct if mct is not None else mt
        if value is not None:
            body[key] = value
        if self.reasoning_effort is not None:
            body["reasoning_effort"] = self.reasoning_effort
        elif not self.reasoning_model:
            body.pop("reasoning_effort", None)
        if self.temperature is not None and "temperature" not in body:
            body["temperature"] = self.temperature
        if self.strips_sampling:
            for k in REASONING_REJECTED:
                body.pop(k, None)
        if self.thinking is not None:
            body.setdefault("chat_template_kwargs", {})["enable_thinking"] = self.thinking
        return body

    def token_key_for(self, body: dict) -> str:
        """The key apply_to_body() will use for the completion cap of `body`."""
        given = "max_completion_tokens" if "max_completion_tokens" in body else "max_tokens"
        return given if (self.token_param_setting == "auto" and not self.reasoning_model) else self.token_param

    def to_dict(self) -> dict:
        d = asdict(self)
        d["dropped"] = list(self.dropped)
        return d


def _env_bool(v: str) -> bool:
    s = v.strip().lower()
    if s in ("1", "true", "yes", "on"):
        return True
    if s in ("0", "false", "no", "off"):
        return False
    raise ValueError(f"expected true/false, got {v!r}")


def resolve_chat_params(model: str | None, settings: Any = None, env: Mapping[str, str] | None = None,
                        *, warn: bool = True) -> ChatParams:
    """Resolve the request parameters for `model` from `settings` (RunConfig.llm, a dict, or None),
    then env vars, then auto-detection. Raises ValueError on an invalid value."""
    env = os.environ if env is None else env
    if settings is not None and not isinstance(settings, Mapping):
        settings = settings.model_dump() if hasattr(settings, "model_dump") else vars(settings)
    settings = dict(settings or {})
    sources: dict[str, str] = {}

    def pick(name: str, parse):
        val = settings.get(name)
        if val is not None:
            sources[name] = "config"
            return val
        raw = (env.get(ENV[name]) or "").strip()
        if raw:
            sources[name] = "env"
            try:
                return parse(raw)
            except ValueError as e:
                raise ValueError(f"{ENV[name]}={raw!r}: {e}") from None
        sources[name] = "auto"
        return None

    reasoning = pick("reasoning_model", _env_bool)
    reasoning = is_reasoning_model(model) if reasoning is None else bool(reasoning)
    setting = pick("token_param", str) or "auto"
    if setting not in TOKEN_PARAMS:
        raise ValueError(f"token_param must be one of {TOKEN_PARAMS}, got {setting!r}")
    token_param = ("max_completion_tokens" if reasoning else "max_tokens") if setting == "auto" else setting
    effort = pick("reasoning_effort", str)
    if effort is not None and effort not in REASONING_EFFORTS:
        raise ValueError(f"reasoning_effort must be one of {REASONING_EFFORTS}, got {effort!r}")
    temperature = pick("temperature", float)
    thinking = pick("thinking", _env_bool)
    dropped: list[str] = []
    if effort is not None and not reasoning:
        dropped.append("reasoning_effort")
        effort = None
    if temperature is not None and reasoning and effort != "none":
        dropped.append("temperature")
        temperature = None
    if thinking is not None and reasoning:
        dropped.append("thinking")  # chat_template_kwargs is vLLM-only; OpenAI rejects it
        thinking = None
    if dropped and warn:
        warnings.warn(f"model {model!r}: not sending {', '.join(dropped)} "
                      f"({'reasoning' if reasoning else 'non-reasoning'} model)")
    return ChatParams(model, reasoning, token_param, setting, effort,
                      None if temperature is None else float(temperature), thinking,
                      tuple(dropped), sources)


