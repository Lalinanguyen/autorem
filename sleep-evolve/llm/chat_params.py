@dataclass(frozen=True)
class Usage:
    prompt_tokens: int
    completion_tokens: int
    cached_tokens: int | None = None      # subset of prompt_tokens (None = not reported)
    reasoning_tokens: int | None = None   # subset of completion_tokens (None = not reported)


def _get(obj: Any, key: str) -> Any:
    if obj is None:
        return None
    return obj.get(key) if isinstance(obj, Mapping) else getattr(obj, key, None)


def _int_or_none(x: Any) -> int | None:
    if x is None or isinstance(x, bool):
        return None
    try:
        return int(x)
    except (TypeError, ValueError):
        return None


def parse_usage(usage: Any) -> Usage | None:
    """Usage from an OpenAI-style usage object or dict; None if prompt/completion counts are missing.

    Works for any OpenAI-compatible server: the details blocks are optional."""
    pt, ct = _int_or_none(_get(usage, "prompt_tokens")), _int_or_none(_get(usage, "completion_tokens"))
    if pt is None or ct is None:
        return None
    cached = _int_or_none(_get(_get(usage, "prompt_tokens_details"), "cached_tokens"))
    reasoning = _int_or_none(_get(_get(usage, "completion_tokens_details"), "reasoning_tokens"))
    return Usage(pt, ct, cached, reasoning)


